// Writes src/d2assets.js: one import per converted texture, so the bundler can inline or fingerprint them.
//   node tools/assets/gen_index.mjs
import fs from 'fs';
const dir = 'src/assets/d2/tex/';
const mats = JSON.parse(fs.readFileSync(dir + 'materials.json', 'utf8'));
const ALIAS = { ground_2: 'ground_1', ground_tile: 'ground_1' };   // identical textures in the pack
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.webp')).sort();
let imp = '', n = 0; const id = {};
for (const f of files) { id[f] = 't' + n++; imp += `import ${id[f]} from './assets/d2/tex/${f}';\n`; }
let out = '// Generated by tools/assets/gen_index.mjs. Do not edit.\n' + imp + 'export const CITY_MATS = {\n';
for (const k of Object.keys(mats)) {
  const b = ALIAS[k] || k, m = mats[k];
  const e = id[`${b}_e.webp`];
  out += `  ${JSON.stringify(k.replace(/_/g, ' '))}: { c: ${id[`${b}_c.webp`]}, n: ${id[`${b}_n.webp`]}, e: ${e || 'null'}, cut: ${m.cut}, metal: ${m.metal}, rough: ${m.rough}, avg: ${JSON.stringify(m.avg)} },\n`;
}
out += '};\n';
fs.writeFileSync('src/d2assets.js', out);
console.log('wrote src/d2assets.js', files.length, 'textures', Object.keys(mats).length, 'materials');
